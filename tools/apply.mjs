function backup(file) {
  // Копии держим в рабочем каталоге скрипта, а не внутри пакета.
  const rel = file.slice(ROOT.length + 1).replace(/[\\/]/g, '__')
  const bak = join(HERE, 'backup', rel + '.zh.bak')
  mkdirSync(join(HERE, 'backup'), { recursive: true })
  if (!existsSync(bak)) copyFileSync(file, bak)
}

function applyRegionFile(rel, regions, rawRules) {
  const file = join(ROOT, rel)
  const text = readFileSync(file, 'utf8')
  const lines = text.split(/\r?\n/)
  let region = '(top)'
  let changed = 0
  const used = new Set()
  const out = lines.map((line) => {
    const m = /^\/\/#region\s+(.+)$/.exec(line)
    if (m) region = m[1]
    let next = line
    const map = regions[region]
    if (map) {
      next = next.replace(/"((?:[^"\\]|\\.)*)"/g, (full, body) => {
        const ru = map[body]
        if (typeof ru === 'string' && ru !== '' && ru !== body) {
          used.add(body)
          changed++
          return '"' + ru + '"'
        }
        return full
      })
      for (const [from, to] of rawRules ?? []) {
        if (next.includes(from)) {
          next = next.split(from).join(to)
          changed++
        }
      }
    }
    return next
  })
  if (dry) {
    console.log(`[dry] ${rel}: строк изменено ${changed}, регионов с правилами ${Object.keys(regions).length}`)
    return
  }
  backup(file)
  writeFileSync(file, out.join('\n'), 'utf8')
  stats.files++
  stats.replaced += changed
  console.log(`${rel}: заменено вхождений ${changed}`)
  if (used.size === 0) console.log(`  ВНИМАНИЕ: ни одна строка не найдена в ${rel}`)
}

function applyConfig() {
  const rel = 'assets/config.jsonc'
  const file = join(ROOT, rel)
  const text = readFileSync(file, 'utf8')
  let next = text
  let changed = 0
  for (const [zh, ru] of Object.entries(configValues)) {
    if (ru === '') continue
    const needle = '"' + zh + '"'
    if (next.includes(needle)) {
      const count = next.split(needle).length - 1
      next = next.split(needle).join('"' + ru + '"')
      changed += count
    }
  }
  if (dry) {
    console.log(`[dry] ${rel}: заменено ${changed}`)
    return
  }
  backup(file)
  writeFileSync(file, next, 'utf8')
  stats.files++
  stats.replaced += changed
  console.log(`${rel}: заменено ${changed}`)
}

function applyPackage() {
  const file = join(ROOT, 'package.json')
  const text = readFileSync(file, 'utf8')
  const before = text
  const next = text.replace(/"description":\s*"(?:[^"\\]|\\.)*"/, '"description": ' + JSON.stringify(pkgDescription))
  if (next === before) {
    console.log('package.json: description не найден')
    return
  }
  if (dry) {
    console.log('[dry] package.json: description')
    return
  }
  backup(file)
  writeFileSync(file, next, 'utf8')
  stats.files++
  console.log('package.json: описание переведено')
}

