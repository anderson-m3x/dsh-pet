const FORBIDDEN = /[\\/:*?"<>|]/
let renamed = 0
let missing = 0
const problems = []

for (const [zh, ru] of Object.entries(anim)) {
  if (FORBIDDEN.test(ru)) problems.push('запрещённый символ в имени: ' + ru)
  const dir = join(ROOT, 'assets', 'webm')
  const from = join(dir, zh + '.webm')
  const to = join(dir, ru + '.webm')
  if (existsSync(from)) {
    if (zh !== ru && existsSync(to)) problems.push('коллизия имён: ' + ru)
    if (!dry && zh !== ru) renameSync(from, to)
    renamed++
  } else if (existsSync(to)) {
    /* уже переименовано */
  } else {
    missing++
  }
}

for (const [zh, ru] of Object.entries(meme)) {
  if (FORBIDDEN.test(ru)) problems.push('запрещённый символ в имени: ' + ru)
  const dir = join(ROOT, 'assets', 'memes')
  const from = join(dir, zh + '.png')
  const to = join(dir, ru + '.png')
  if (existsSync(from)) {
    if (zh !== ru && existsSync(to)) problems.push('коллизия имён: ' + ru)
    if (!dry && zh !== ru) renameSync(from, to)
    renamed++
  } else if (existsSync(to)) {
    /* уже переименовано */
  } else {
    missing++
  }
}

const cfgPath = join(ROOT, 'assets', 'config.jsonc')
const cfg = readFileSync(cfgPath, 'utf8')
let next = cfg
let replaced = 0
for (const [zh, ru] of Object.entries({ ...anim, ...meme })) {
  const needle = '"' + zh + '"'
  const count = next.split(needle).length - 1
  if (count > 0) {
    next = next.split(needle).join('"' + ru + '"')
    replaced += count
  }
}

if (!dry) writeFileSync(cfgPath, next, 'utf8')

/** Проверка: каждое имя из конфига имеет файл. */
const check = readFileSync(cfgPath, 'utf8')
const names = [...check.matchAll(/"([^"]+)"\.webm|"([^"]+)"\s*:\s*"[^"]*"/g)]
const webmFiles = new Set(readdirSync(join(ROOT, 'assets', 'webm')).filter((f) => f.endsWith('.webm')).map((f) => f.slice(0, -5)))
const missingAnim = Object.values(anim).filter((n) => !webmFiles.has(n) && !names.some((m) => m[1] === n))

console.log(JSON.stringify({ renamedFiles: renamed, missingAssets: missing, configReplacements: replaced, problems: problems.slice(0, 10), animFilesWithoutMatch: missingAnim, dry }, null, 2))
